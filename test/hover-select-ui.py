import json
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
from ui_controls import open_current_space_delete, space_picker, select_space

BASE = 'http://127.0.0.1:3100'
f = json.loads(Path('data/iteration29-fixture.json').read_text(encoding='utf-8'))

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True)
    page = browser.new_page(viewport={'width': 1280, 'height': 900})
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto(BASE)
    page.wait_for_load_state('networkidle')
    space = space_picker(page)
    persona = page.get_by_role('combobox', name='讲解风格', exact=True)
    spaces = page.get_by_role('listbox', name='切换空间', exact=True)
    personas = page.get_by_role('listbox', name='讲解风格', exact=True)
    concept = page.get_by_placeholder('想搞懂什么概念？如：正弦波的频率、英语名词复数、快速排序', exact=True)

    # Opening on hover must not steal the current input focus or change selection.
    concept.fill('保留正在输入的概念')
    concept.focus()
    space.hover()
    expect(spaces).to_be_visible()
    expect(concept).to_be_focused()
    expect(space).to_have_attribute('data-value', '')
    spaces.get_by_role('option', name='全局', exact=True).hover()
    page.wait_for_timeout(220)
    expect(spaces).to_be_visible()
    assert spaces.evaluate('(node) => node.scrollHeight > node.clientHeight'), 'Long list must scroll internally'
    persona.hover()
    expect(personas).to_be_visible()
    expect(spaces).to_have_count(0)
    expect(personas.get_by_role('option', name='自定义', exact=True)).to_be_in_viewport()
    personas.get_by_role('option', name='严谨学者', exact=True).hover()
    page.wait_for_timeout(220)
    expect(personas).to_be_visible()
    personas.locator('..').screenshot(path='data/iteration29-persona.png')
    personas.get_by_role('option', name='严谨学者', exact=True).click()
    expect(persona).to_have_attribute('data-value', 'scholar')
    expect(personas).to_have_count(0)
    expect(concept).to_have_value('保留正在输入的概念')

    space.hover()
    long_option = spaces.get_by_role('option', name=f['long']['name'], exact=True)
    long_option.scroll_into_view_if_needed()
    long_option.hover()
    expect(long_option).to_be_visible()
    spaces.locator('..').screenshot(path='data/iteration29-spaces.png')
    long_option.click()
    expect(space).to_have_attribute('data-value', str(f['long']['id']))
    expect(page.get_by_role('heading', name='今天从这里开始')).to_be_visible()
    # Pointer leaving, outside click, and Escape dismiss without changing values.
    persona.hover()
    page.mouse.move(0, 0)
    expect(personas).to_have_count(0)
    persona.hover()
    concept.click()
    expect(personas).to_have_count(0)
    persona.hover()
    page.keyboard.press('Escape')
    expect(personas).to_have_count(0)

    # Keyboard focus stays on the trigger, with active-descendant navigation.
    space.focus()
    space.press('Home')
    expect(spaces).to_be_visible()
    space.press('Enter')
    expect(space).to_have_attribute('data-value', '')
    space.press('End')
    expect(page.locator('[id="' + space.get_attribute('aria-activedescendant') + '"]')).to_have_attribute('data-value', '__new__')
    space.press('Escape')
    space.press('a')
    expect(page.locator('[id="' + space.get_attribute('aria-activedescendant') + '"]')).to_have_attribute('data-value', str(f['alpha']['id']))
    space.press(' ')
    expect(space).to_have_attribute('data-value', str(f['alpha']['id']))
    persona.focus()
    persona.press('ArrowDown')
    persona.press('Home')
    persona.press('ArrowDown')
    persona.press('ArrowUp')
    persona.press('Enter')
    expect(persona).to_have_attribute('data-value', 'default')
    persona.press('ArrowDown')
    persona.press('Tab')
    expect(personas).to_have_count(0)
    assert not persona.evaluate('(node) => node === document.activeElement')

    persona.click()
    personas.get_by_role('option', name='自定义', exact=True).click()
    custom = page.get_by_placeholder('一句话描述人设…', exact=True)
    custom.fill('用简短的生活例子解释每个术语')
    page.reload()
    expect(persona).to_have_attribute('data-value', 'custom')
    expect(custom).to_have_value('用简短的生活例子解释每个术语')
    concept.fill('菜单验收概念')
    with page.expect_request(lambda request: request.url.endswith('/api/generate') and request.method == 'POST') as generated:
        page.get_by_role('button', name='生成讲解', exact=True).click()
    assert generated.value.post_data_json['personaStyle'] == '用简短的生活例子解释每个术语'
    expect(persona).to_be_enabled()
    expect(page.get_by_role('button', name='🔖 制成复习卡', exact=True)).to_be_visible()
    persona.click()
    personas.get_by_role('option', name='严谨学者', exact=True).click()
    concept.fill('菜单预设风格验收')
    with page.expect_request(lambda request: request.url.endswith('/api/generate') and request.method == 'POST') as generated:
        page.get_by_role('button', name='生成讲解', exact=True).click()
    assert generated.value.post_data_json['personaStyle'].startswith('用语准确严谨')
    expect(persona).to_be_enabled()
    expect(page.get_by_role('button', name='🔖 制成复习卡', exact=True)).to_be_visible()

    # A short viewport must flip the popup above its trigger and retain viewport bounds.
    page.set_viewport_size({'width': 763, 'height': 420})
    persona.hover()
    expect(personas).to_be_visible()
    bounds = personas.locator('..').bounding_box()
    trigger_bounds = persona.bounding_box()
    assert bounds['y'] >= 0 and bounds['y'] + bounds['height'] <= trigger_bounds['y'] + 1, (bounds, trigger_bounds)
    assert bounds['x'] >= 0 and bounds['x'] + bounds['width'] <= 763
    page.keyboard.press('Escape')
    page.set_viewport_size({'width': 390, 'height': 844})
    space.hover()
    expect(spaces).to_be_visible()
    bounds = spaces.locator('..').bounding_box()
    assert bounds['x'] >= 0 and bounds['x'] + bounds['width'] <= 390
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    page.keyboard.press('Escape')
    # New space action and deletion continue to work through the new menu.
    space.click()
    spaces.get_by_role('option', name='新建空间', exact=True).click()
    name = page.get_by_placeholder('空间名，如：期末·操作系统', exact=True)
    expect(name).to_be_focused()
    name.fill(f['newName'])
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    with page.expect_response(lambda response: response.url == BASE + '/api/spaces' and response.request.method == 'POST') as created:
        page.get_by_role('button', name='创建', exact=True).click()
    new_id = created.value.json()['id']
    expect(space).to_have_attribute('data-value', str(new_id))
    space.hover()
    expect(spaces.get_by_role('option', name=f['newName'], exact=True)).to_have_attribute('aria-selected', 'true')
    page.keyboard.press('Escape')
    open_current_space_delete(page)
    page.get_by_role('alertdialog').get_by_role('button', name='彻底删除空间', exact=True).click()
    expect(space).to_have_attribute('data-value', '')

    # Coarse-pointer touch needs no hover gesture.
    touch = browser.new_context(viewport={'width': 390, 'height': 844}, is_mobile=True, has_touch=True)
    mobile = touch.new_page()
    mobile.on('pageerror', lambda error: errors.append(str(error)))
    mobile.goto(BASE)
    mobile.wait_for_load_state('networkidle')
    mobile_space = space_picker(mobile)
    mobile_space.tap()
    mobile.get_by_role('listbox', name='切换空间', exact=True).get_by_role('option', name=f['alpha']['name'], exact=True).tap()
    expect(mobile_space).to_have_attribute('data-value', str(f['alpha']['id']))
    mobile_persona = mobile.get_by_role('combobox', name='讲解风格', exact=True)
    mobile_persona.tap()
    mobile.get_by_role('listbox', name='讲解风格', exact=True).get_by_role('option', name='轻松伙伴', exact=True).tap()
    expect(mobile_persona).to_have_attribute('data-value', 'buddy')
    assert mobile.evaluate('document.documentElement.scrollWidth <= innerWidth')
    mobile_persona.tap()
    mobile.screenshot(path='data/iteration29-touch.png', full_page=True)
    touch.close()
    assert not errors, errors
    print('PASS: hover continuity, focus preservation, exclusivity, selection, dismissal, keyboard/typeahead, custom/preset request, persistence, long labels/lists, viewport flip, narrow creation, touch')
    browser.close()
