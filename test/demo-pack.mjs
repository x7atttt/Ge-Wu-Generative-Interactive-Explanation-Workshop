import assert from "node:assert/strict";
import { mkdtempSync, readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { DatabaseSync } from "node:sqlite";

const workspace = mkdtempSync(join(tmpdir(), "gewu-demo-"));
const run = (command, args = [], success = true, target = workspace) => {
  const result = spawnSync(process.execPath, ["scripts/demo-pack.mjs", command, `--workspace=${target}`, ...args], { encoding: "utf8" });
  assert.equal(result.status === 0, success, result.stdout + result.stderr);
  return result.stdout;
};
run("check");
run("import");
const db = new DatabaseSync(join(workspace, "data/gewu.db"));
const counts = () => ["spaces", "sources", "docs", "attempts", "asks", "cards"].map(table => db.prepare(`SELECT count(*) AS n FROM ${table}`).get().n);
assert.deepEqual(counts(), [1, 2, 3, 0, 0, 0]);
assert.match(run("import"), /跳过/);
assert.deepEqual(counts(), [1, 2, 3, 0, 0, 0]);
const rows = db.prepare("SELECT * FROM docs ORDER BY id").all();
assert.equal(rows[1].parent_id, rows[0].id);
assert.deepEqual(JSON.parse(rows[1].doc).blocks.slice(0, JSON.parse(rows[0].doc).blocks.length), JSON.parse(rows[0].doc).blocks);
for (const row of rows) {
  assert.equal(row.space_id, 1);
  for (const id of JSON.parse(row.source_ids)) assert.ok(db.prepare("SELECT id FROM sources WHERE id=? AND space_id=?").get(id, row.space_id));
  for (const source of JSON.parse(row.source_context).sources) assert.ok(db.prepare("SELECT id FROM sources WHERE id=?").get(source.id));
}
db.prepare("INSERT INTO spaces(name,note) VALUES('我的资料','保留')").run();
const exported = join(workspace, "roundtrip.json");
run("export", ["--space=1", `--out=${exported}`]);
run("export", ["--space=1", `--out=${exported}`], false);
const other = mkdtempSync(join(tmpdir(), "gewu-demo-roundtrip-"));
run("import", [`--file=${exported}`], true, other);
const roundtrip = new DatabaseSync(join(other, "data/gewu.db"), { readOnly: true });
assert.equal(roundtrip.prepare("SELECT count(*) AS n FROM docs").get().n, 3);
assert.equal(roundtrip.prepare("SELECT count(*) AS n FROM docs WHERE parent_id IS NOT NULL").get().n, 1);
roundtrip.close();
const pack = JSON.parse(readFileSync("demo/showcase.json", "utf8"));
const badFile = join(workspace, "bad.json");
pack.lessons[0].sources = ["missing"];
writeFileSync(badFile, JSON.stringify(pack));
const invalid = mkdtempSync(join(tmpdir(), "gewu-demo-invalid-"));
run("import", [`--file=${badFile}`], false, invalid);
assert.equal(existsSync(join(invalid, "data/gewu.db")), false);
pack.lessons[0].sources = ["wave-notes"];
pack.name = "已修改";
writeFileSync(badFile, JSON.stringify(pack));
run("import", [`--file=${badFile}`], false);
assert.equal(db.prepare("SELECT count(*) AS n FROM spaces").get().n, 2);
pack.id = "second-demo";
writeFileSync(badFile, JSON.stringify(pack));
db.exec("CREATE TRIGGER fail_demo BEFORE INSERT ON docs BEGIN SELECT RAISE(ABORT,'test rollback'); END");
run("import", [`--file=${badFile}`], false);
assert.deepEqual(counts(), [2, 2, 3, 0, 0, 0]);
assert.equal(db.prepare("SELECT count(*) AS n FROM demo_imports").get().n, 1);
db.exec("DROP TRIGGER fail_demo");
run("import", [`--file=${badFile}`]);
assert.equal(db.prepare("SELECT note FROM spaces WHERE name='我的资料'").get().note, "保留");
const backups = readdirSync(join(workspace, "data/backups"));
assert.equal(backups.length, 2);
const backup = new DatabaseSync(join(workspace, "data/backups", backups[0]), { readOnly: true });
assert.equal(backup.prepare("SELECT count(*) AS n FROM spaces").get().n, 2);
backup.close();
assert.equal(db.prepare("PRAGMA integrity_check").get().integrity_check, "ok");
db.close();
console.log(`PASS 演示包：版本/资料关联、幂等、隔离、备份、非法输入与导出回读；产物 ${resolve(workspace)}`);
